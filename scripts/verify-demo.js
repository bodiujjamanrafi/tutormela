import assert from 'node:assert/strict'
import {createDemoSession} from '../src/lib/demo.js'
const demo=createDemoSession()
assert.equal(demo.handles('/auth/login','POST'),false)
assert.throws(()=>demo.request('/auth/demo','POST',{email:'test@example.com',password:'test',role:'admin'}))
assert.throws(()=>demo.request('/auth/demo','POST',{email:'invalid',password:'test',role:'student'}))
assert.throws(()=>demo.request('/auth/demo','POST',{email:'test@example.com',password:'',role:'student'}))
const tutor=demo.request('/auth/demo','POST',{email:'tutor@example.com',password:'test-only',role:'tutor'}).user
assert.equal(tutor.role,'tutor')
assert.equal(tutor.demo,true)
assert.equal(JSON.stringify(demo.request('/me')).includes('test-only'),false)
assert.equal(demo.handles('/profiles','GET'),false)
assert.equal(demo.handles('/catalog','GET'),false)
assert.equal(demo.handles('/admin/profiles','GET'),true)
assert.throws(()=>demo.request('/admin/profiles'))
const profile=demo.request('/profile')
demo.request('/account','PUT',{name:'Test Tutor',role:'admin'})
assert.equal(demo.request('/me').user.name,'Test Tutor')
assert.equal(demo.request('/me').user.role,'tutor')
demo.request('/profile','PUT',{name:'Test Tutor',draft:true,id:'overwrite-attempt'})
assert.equal(demo.request('/profile').id,profile.id)
assert.throws(()=>demo.request('/statuses','POST',{body:'Hello',consent:true}))
demo.request('/statuses','POST',{body:'Available for Mathematics lessons after school.',consent:true})
const status=demo.request(`/statuses?profile=${profile.id}&owner=1`)[0]
assert.ok(status.body.includes('Mathematics'))
demo.request(`/statuses/${status.id}`,'PATCH',{visible:false})
assert.ok(demo.request(`/statuses?profile=${profile.id}`)[0].withdrawn_at)
assert.deepEqual(demo.request('/statuses?profile=someone-else'),[])
demo.request('/auth/logout','POST')
assert.equal(demo.active,false)
assert.equal(demo.handles('/account','PUT'),false)
const student=demo.request('/auth/demo','POST',{email:'student@example.com',password:'test-only',role:'student'}).user
assert.equal(student.role,'student')
assert.deepEqual(demo.request('/requests'),[])
assert.throws(()=>demo.request('/requests','POST',{profileId:'real-profile'}))
assert.throws(()=>demo.request('/profile','PUT',{name:'Not a tutor'}))
assert.throws(()=>demo.request('/statuses','POST',{body:'Attempt to post as a student.',consent:true}))
// The same browser can switch test roles and exercise real temporary engagement.
demo.request('/auth/logout','POST')
demo.request('/auth/demo','POST',{email:'tutor@example.com',password:'test-only',role:'tutor'})
assert.equal(demo.request('/me').user.name,'Test Tutor')
const shared=demo.request('/profile','PUT',{name:'Test Tutor',subjects:['Mathematics'],classes:['Class 9–10 / SSC'],aboutEn:'Available for Mathematics tuition after school.',draft:false,consent:true})
const identity=demo.request('/feed')[0]
assert.equal(identity.profile.id,shared.id)
assert.equal(identity.owner,true)
demo.request('/auth/logout','POST')
demo.request('/auth/demo','POST',{email:'student@example.com',password:'test-only',role:'student'})
assert.equal(demo.request('/feed')[0].owner,false)
demo.request(`/feed/${identity.id}/reaction`,'POST',{reacted:true})
demo.request(`/feed/${identity.id}/reaction`,'POST',{reacted:true})
demo.request('/views','POST',{kind:'post',target:identity.id})
demo.request('/views','POST',{kind:'post',target:identity.id})
demo.request('/views','POST',{kind:'profile',target:shared.id})
assert.equal(demo.request('/feed')[0].reactions,1)
assert.throws(()=>demo.request(`/statuses/${identity.id}`,'PUT',{body:'Trying to edit someone else’s identity.'}))
demo.request('/auth/logout','POST')
demo.request('/auth/demo','POST',{email:'tutor@example.com',password:'test-only',role:'tutor'})
const engagement=demo.request('/analytics')
assert.equal(engagement.profileViews,1)
assert.equal(engagement.posts.find(p=>p.id===identity.id).views,1)
assert.equal(engagement.posts.find(p=>p.id===identity.id).reactions,1)
demo.request('/profile/hide','POST')
assert.deepEqual(demo.request('/feed'),[])
console.log('Demo checks passed: both roles, direct profile access, edits and tutor statuses, credential privacy, and isolation from real account actions.')
